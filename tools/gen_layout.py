#!/usr/bin/env python3
"""Generate field-offset tables for the harness (build-time helper).

Usage:
    python gen_layout.py MatrixGame/src

Writes SimLayoutRobot.inc and SimLayoutAI.inc next to the sources. The harness
includes them inside member functions, where private members are accessible, so
raw offsets reported by the fill scanner can be mapped back to field names.
"""

import re
import sys
from pathlib import Path

IDENT_RE = re.compile(r"([A-Za-z_]\w*)\s*$")


def class_body(text, class_name):
    needle = "class %s" % class_name
    start = -1
    pos = 0
    while True:
        pos = text.find(needle, pos)
        if pos < 0:
            raise SystemExit("class %s not found" % class_name)
        line_end = text.find("\n", pos)
        head = text[pos:line_end]
        # Skip forward declarations like "class CMatrixMapStatic;".
        if not head.rstrip().endswith(";") and "{" in text[pos:text.find("{", pos) + 1]:
            start = pos
            break
        pos += len(needle)

    brace = text.index("{", start)
    depth = 0
    for i in range(brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[brace + 1:i]
    raise SystemExit("unbalanced braces in %s" % class_name)


def split_top_level(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return parts


def members(body):
    out = []
    skip = 0
    depth = 0
    for raw in body.splitlines():
        line = raw.split("//")[0].strip()
        if not line:
            continue
        if depth == 0 and line.startswith("#if"):
            skip += 1
            continue
        if depth == 0 and line.startswith("#endif"):
            skip = max(0, skip - 1)
            continue

        opens = line.count("{")
        closes = line.count("}")
        at_top = depth == 0
        depth = max(0, depth + opens - closes)
        if not at_top or opens or closes:
            continue
        if skip or line.startswith(("static ", "typedef ", "using ", "friend ", "enum ", "struct ", "union ")):
            continue
        if not line.endswith(";"):
            continue
        if "(" in line or ")" in line:
            continue

        for part in split_top_level(line.rstrip(";")):
            part = part.split("=")[0].strip()
            if not part:
                continue
            if part.endswith("]"):
                part = part[: part.index("[")].strip()
            part = part.split(":")[0].strip()
            m = IDENT_RE.search(part)
            if not m:
                continue
            name = m.group(1)
            if name in ("public", "private", "protected", "false", "true", "NULL", "return"):
                continue
            if name not in out:
                out.append(name)
    return out


def emit(path, cls, names):
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_layout.py - member offsets for the harness.\n")
        for n in names:
            f.write("OFFSET_OF(%s, %s);\n" % (cls, n))
    return len(names)


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "MatrixGame/src")
    static = members(class_body((src / "MatrixMapStatic.hpp").read_text(encoding="utf-8", errors="replace"),
                                "CMatrixMapStatic"))
    robot = members(class_body((src / "MatrixObjectRobot.hpp").read_text(encoding="utf-8", errors="replace"),
                               "CMatrixRobot"))
    ai = members(class_body((src / "MatrixRobot.hpp").read_text(encoding="utf-8", errors="replace"),
                            "CMatrixRobotAI"))
    n0 = emit(src / "SimLayoutStatic.inc", "CMatrixMapStatic", static)
    n1 = emit(src / "SimLayoutRobot.inc", "CMatrixRobot", robot)
    n2 = emit(src / "SimLayoutAI.inc", "CMatrixRobotAI", ai)
    print("CMatrixMapStatic: %d fields, CMatrixRobot: %d fields, CMatrixRobotAI: %d fields" % (n0, n1, n2))


if __name__ == "__main__":
    main()
